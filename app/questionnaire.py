def blocks_for(is_manager):
    """Блоки анкеты; блок M — только при оценке руководителя."""
    return [b for b in BLOCKS if is_manager or not b["manager_only"]]


def score_keys(is_manager):
    """Ключи утверждений со шкалой 1–5 в порядке анкеты."""
    return [i["key"] for b in blocks_for(is_manager) for i in b["items"]]


def text_keys(is_manager):
    """Ключи текстовых ответов: комментарии блоков, открытые вопросы, дополнительные комментарии."""
    keys = {"c:" + b["key"] for b in blocks_for(is_manager)}
    keys.update(q["key"] for q in OPEN_QUESTIONS)
    keys.add(EXTRA_KEY)
    return keys


def check_answer(key, value, is_manager):
    """Проверяет ответ и возвращает значение для записи; None — ответ удалить. Иначе BadRequest."""
    if not isinstance(key, str):  # список или словарь вместо ключа сломал бы поиск по множеству ключей
        raise BadRequest("Неизвестный вопрос")
    if key in score_keys(True):
        if key not in score_keys(is_manager):
            raise BadRequest("Блок M заполняется только при оценке руководителя")
        if value is None or value == "":
            return None
        if isinstance(value, bool):
            raise BadRequest("Оценка должна быть целым числом от 1 до 5")
        if isinstance(value, str):
            value = value.strip()
            if not value.isdigit() or not value.isascii():
                raise BadRequest("Оценка должна быть целым числом от 1 до 5")
            value = int(value)
        if not isinstance(value, int) or not 1 <= value <= 5:
            raise BadRequest("Оценка должна быть целым числом от 1 до 5")
        return str(value)
    if key in text_keys(True):
        if key not in text_keys(is_manager):
            raise BadRequest("Блок M заполняется только при оценке руководителя")
        if value is None or value == "":
            return None
        if not isinstance(value, str):
            raise BadRequest("Ответ должен быть текстом")
        if len(value) > MAX_TEXT:
            raise BadRequest("Ответ длиннее 5000 символов")
        return value
    raise BadRequest("Неизвестный вопрос")
